import { mkdtempSync, rmSync, symlinkSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { expect, it } from "vitest";
import {
  fileSchemaPackageLockCommand,
  generateFileSchemaPackageLock,
} from "./file-schema-package-commands";

const packageId = "file-schema-evolution-workshop";
function withRoot(test: (root: string) => void) {
  const root = mkdtempSync(join(tmpdir(), "file-schema-lock-toy-"));
  try {
    test(root);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
}

it("plans exactly one offline owned manifest lock command for the new package", () => {
  expect(fileSchemaPackageLockCommand(packageId, "/owned/root")).toEqual([
    "generate-lockfile",
    "--offline",
    "--manifest-path",
    "/owned/root/Cargo.toml",
  ]);
  for (const id of ["todo-cli-workshop", "file-schema-evolution", "other"]) {
    expect(fileSchemaPackageLockCommand(id, "/owned/root")).toEqual([]);
  }
});

it("requires successful generation and rejects missing or pre-existing lock files", () =>
  withRoot((root) => {
    expect(() =>
      generateFileSchemaPackageLock(packageId, root, () => false),
    ).toThrow(/generation failed/i);
    expect(() =>
      generateFileSchemaPackageLock(packageId, root, () => true),
    ).toThrow();
    const lock = join(root, "Cargo.lock");
    writeFileSync(lock, "preexisting");
    let calls = 0;
    expect(() =>
      generateFileSchemaPackageLock(packageId, root, () => {
        calls++;
        return true;
      }),
    ).toThrow();
    expect(calls).toBe(0);
  }));

it("pins actual generated bytes and refuses symlinks or changed lock bytes", () =>
  withRoot((root) => {
    const lock = join(root, "Cargo.lock");
    const receipt = generateFileSchemaPackageLock(packageId, root, (argv) => {
      expect(argv).toEqual(fileSchemaPackageLockCommand(packageId, root));
      writeFileSync(lock, "version = 4\n", { flag: "wx" });
      return true;
    })!;
    expect(receipt.binding.bytes).toBe(12);
    expect(() => receipt.assertUnchanged()).not.toThrow();
    writeFileSync(lock, "version = 3\n");
    expect(() => receipt.assertUnchanged()).toThrow();
    rmSync(lock);
    expect(() =>
      generateFileSchemaPackageLock(packageId, root, () => {
        symlinkSync("missing", lock);
        return true;
      }),
    ).toThrow();
  }));
