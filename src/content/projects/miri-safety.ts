const safetyTests = String.raw`use miri_safety_workshop::{ByteView, MutSlot, Slot, SlotState, split_regions};

#[test]
fn byte_view_borrows_initialized_bytes_without_owning_them() {
    let input = [10, 20];
    let view = ByteView::from_slice(&input);
    assert_eq!(view.as_slice(), &[10, 20]);
    assert_eq!(ByteView::from_slice(&[]).as_slice(), &[]);
}

#[test]
fn split_regions_are_disjoint() {
    let mut input = [1, 2, 3, 4];
    let (left, right) = split_regions(&mut input, 2).expect("valid split");
    left[0] = 9;
    right[0] = 8;
    assert_eq!(left, [9, 2]);
    assert_eq!(right, [8, 4]);
    assert!(split_regions(&mut input, 5).is_none());
}

#[test]
fn slot_transfers_values_and_rejects_a_second_put() {
    let mut slot = Slot::empty();
    assert_eq!(slot.state(), SlotState::Empty);
    assert_eq!(slot.put(7_u32), Ok(()));
    assert_eq!(slot.state(), SlotState::Full);
    assert_eq!(slot.put(8_u32), Err(8));
    assert_eq!(slot.take(), Some(7));
    assert_eq!(slot.take(), None);
}

#[test]
fn mut_slot_reborrow_releases_the_outer_slot() {
    let mut value = 3;
    let mut slot = MutSlot::new(&mut value);
    {
        let mut short = slot.reborrow();
        *short.get_mut() += 1;
    }
    *slot.get_mut() += 2;
    assert_eq!(value, 6);
}
`;

