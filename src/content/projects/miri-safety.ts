const safety = String.raw`# Safety ledger

The main crate has \`#![forbid(unsafe_code)]\`. Its contracts are deliberately
small:

- \`ByteView\` borrows an existing initialized slice without taking ownership or
  extending its lifetime.
- \`split_regions\` delegates the disjointness proof to the standard library and
  returns no pair when the split is outside the slice.
- \`Slot<T>\` represents Empty/Full state and transfers each stored value once;
  \`MutSlot\` can shorten only its outer borrow through a reborrow.

The three files under \`fixtures/\` are negative examples. Each one violates a
different memory rule and must be observed through Miri. They are kept outside
the library crate so an accidental native test run cannot make them part of a
normal package test.
`;

