const readme = `# FFI buffer workshop

This package is a deliberately small Rust 2024 FFI boundary. Rust owns a
native buffer after a successful \`ffi_buffer_create\`, borrows its immutable
view, and calls \`ffi_buffer_destroy\` exactly once from \`Drop\`.

## Run it

The fixture needs a C compiler and archiver named by \`CC\` and \`AR\`, or the
usual \`cc\` and \`ar\` on PATH. Rust 1.85.0 is the minimum supported toolchain.

\`\`\`sh
cargo fmt --all -- --check
cargo check --locked
cargo test --locked
cargo test --locked --test native_integration -- --test-threads=1
cargo clippy --all-targets --locked -- -D warnings
\`\`\`

The C fixture rejects a buffer longer than 4096 bytes, a null non-empty input,
and an input whose first byte is \`0xff\`. The last case is an intentional,
deterministic failure so the Rust wrapper test proves that native failure is
reported instead of converted into a dangling owner.

The native fixture also exposes a deterministic release counter for the
integration test. Run that test with one test thread so the counter is scoped
to its probe and a missing \`Drop\` call cannot pass accidentally.

## Contract

The C side copies caller bytes during create. On success it returns one owned
handle. The handle remains valid until destroy, and the view pointer remains
valid while the Rust \`Buffer\` is borrowed. The Rust wrapper checks its input
bound, rejects a null create result, checks the returned length, and keeps all
raw pointers private.

The starter contains TODOs in the Rust declarations and wrapper. Complete it
without weakening the tests or moving ownership into a caller-managed raw
pointer.

## Limits

This is a teaching fixture, not a general allocator abstraction. It does not
promise thread-safe mutation, transfer of a C handle to another allocator, or
recovery from a malicious native library that violates its declared ABI. The
safe API can check the documented bound and null result; it cannot prove that
arbitrary foreign code obeys the contract.
`;

const safety = `# Safety ledger

| Boundary | Assumption | Rust proof or containment |
| --- | --- | --- |
| \`ffi_buffer_create\` | The C ABI accepts a pointer/length pair and copies bytes before returning. | \`from_bytes\` passes a slice pointer and length, checks the maximum, and treats null as an error. |
| \`ffi_buffer_view\` | A successful handle owns an immutable allocation until destroy. | \`view\` borrows through \`&self\`, checks null/length, and constructs one slice only after those checks. |
| \`ffi_buffer_destroy\` | The handle was returned by create and has not been destroyed. | \`NonNull\` is stored in one non-\`Copy\` owner; \`Drop\` is the only release site. |
| C layout | The opaque pointer is never dereferenced by Rust. | \`sys::ffi_buffer_t\` is an opaque \`repr(C)\` type and raw access stays in \`sys\`. |

The C fixture's sentinel failure is a test oracle, not an allocator guarantee.
The Rust wrapper still handles any null create result conservatively. A view
whose pointer and nonzero length disagree is reported as
\`BufferError::NativeInvariant\` rather than passed to \`from_raw_parts\`.
`;

