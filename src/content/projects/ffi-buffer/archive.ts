const native = String.raw`#include "ffi_buffer.h"

#include <stdlib.h>
#include <string.h>

struct FfiBuffer {
    uint8_t *data;
    size_t len;
};

static _Thread_local size_t release_count;

FfiBuffer *ffi_buffer_create(const uint8_t *data, size_t len) {
    if (len > FFI_BUFFER_MAX_LEN || (len != 0 && data == NULL)) {
        return NULL;
    }
    if (len != 0 && data[0] == FFI_BUFFER_FAILURE_SENTINEL) {
        return NULL;
    }

    FfiBuffer *buffer = malloc(sizeof(*buffer));
    if (buffer == NULL) {
        return NULL;
    }
    buffer->data = NULL;
    buffer->len = len;
    if (len != 0) {
        buffer->data = malloc(len);
        if (buffer->data == NULL) {
            free(buffer);
            return NULL;
        }
        memcpy(buffer->data, data, len);
    }
    return buffer;
}

const uint8_t *ffi_buffer_view(const FfiBuffer *buffer, size_t *len) {
    if (len == NULL) {
        return NULL;
    }
    if (buffer == NULL) {
        *len = 0;
        return NULL;
    }
    *len = buffer->len;
    return buffer->data;
}

void ffi_buffer_destroy(FfiBuffer *buffer) {
    if (buffer == NULL) {
        return;
    }
    release_count += 1;
    free(buffer->data);
    free(buffer);
}

size_t ffi_buffer_release_count(void) {
    return release_count;
}

void ffi_buffer_reset_release_count(void) {
    release_count = 0;
}
`;

