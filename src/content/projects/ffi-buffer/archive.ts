const libSolution = String.raw`#![deny(unsafe_op_in_unsafe_fn)]
//! A small safe owner for a C allocated byte buffer.
//!
//! The only unsafe operations are the three calls at the ABI boundary and the
//! checked conversion of the native view into a Rust slice. The C fixture owns
//! its allocation after a successful create and the Rust owner releases it in Drop.

mod sys;

pub const MAX_LEN: usize = 4096;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum BufferError {
    TooLong { actual: usize, maximum: usize },
    NativeCreateFailed,
    NativeInvariant,
}

pub struct Buffer {
    raw: std::ptr::NonNull<sys::ffi_buffer_t>,
}

impl Buffer {
    pub fn from_bytes(bytes: &[u8]) -> Result<Self, BufferError> {
        if bytes.len() > MAX_LEN {
            return Err(BufferError::TooLong {
                actual: bytes.len(),
                maximum: MAX_LEN,
            });
        }

        let raw = unsafe { sys::ffi_buffer_create(bytes.as_ptr(), bytes.len()) };
        let raw = std::ptr::NonNull::new(raw).ok_or(BufferError::NativeCreateFailed)?;
        Ok(Self { raw })
    }

    pub fn view(&self) -> Result<&[u8], BufferError> {
        let mut len = 0usize;
        let ptr = unsafe { sys::ffi_buffer_view(self.raw.as_ptr(), &mut len) };
        if ptr.is_null() {
            return if len == 0 {
                Ok(&[])
            } else {
                Err(BufferError::NativeInvariant)
            };
        }
        if len > MAX_LEN {
            return Err(BufferError::NativeInvariant);
        }
        // The native owner keeps ptr valid and immutable for the lifetime of self.
        Ok(unsafe { std::slice::from_raw_parts(ptr, len) })
    }
}

impl Drop for Buffer {
    fn drop(&mut self) {
        unsafe { sys::ffi_buffer_destroy(self.raw.as_ptr()) };
    }
}
`;

