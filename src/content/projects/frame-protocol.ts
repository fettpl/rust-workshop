//! Bounded, u16-prefixed frames with a deliberately small public API.
//!
//! \`Frame\` has private representation. A client obtains it through
//! \`Frame::try_from_payload\`, but cannot construct an unchecked value.
//!
//! \`\`\`compile_fail
