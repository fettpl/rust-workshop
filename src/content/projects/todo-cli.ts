const appSolution = `use crate::command::{Command, CommandError, parse_command};
use crate::storage::{StorageError, load, save};

#[derive(Debug)]
pub enum AppError {
    Command(CommandError),
    Storage(StorageError),
}

pub fn execute(path: &str, line: &str) -> Result<String, AppError> {
    let command = match parse_command(line) {
        Ok(command) => command,
        Err(error) => return Err(AppError::Command(error)),
    };
    let changes_state = match &command {
        Command::Add(_) | Command::Done(_) => true,
        Command::List => false,
    };
    let mut todo = match load(path) {
        Ok(todo) => todo,
        Err(error) => return Err(AppError::Storage(error)),
    };
    let text = match todo.apply(command) {
        Ok(text) => text,
        Err(error) => return Err(AppError::Command(error)),
    };
    if changes_state {
        match save(path, &todo) {
            Ok(()) => {}
            Err(error) => return Err(AppError::Storage(error)),
        }
    }
    Ok(text)
}
`;

