const command = `#[derive(Debug, PartialEq, Eq)]
pub enum Command {
    Add(String),
    Done(usize),
    List,
}

#[derive(Debug, PartialEq, Eq)]
pub enum CommandError {
    Empty,
    Unknown,
    InvalidTitle,
    InvalidId,
    NotFound,
}

pub fn parse_command(line: &str) -> Result<Command, CommandError> {
    let line = line.trim();
    if line.is_empty() {
        return Err(CommandError::Empty);
    }
    let (verb, argument) = match line.split_once(' ') {
        Some(parts) => parts,
        None => (line, ""),
    };
    match verb {
        "add" => {
            let title = argument.trim();
            if title.is_empty() || title.contains('\\n') || title.contains('\\r') {
                Err(CommandError::InvalidTitle)
            } else {
                Ok(Command::Add(String::from(title)))
            }
        }
        "done" => {
            let id = argument.trim();
            if id.is_empty() || id.starts_with('+') {
                return Err(CommandError::InvalidId);
            }
            for character in id.chars() {
                if !character.is_ascii_digit() {
                    return Err(CommandError::InvalidId);
                }
            }
            match id.parse::<usize>() {
                Ok(value) if value > 0 => Ok(Command::Done(value)),
                _ => Err(CommandError::InvalidId),
            }
        }
        "list" => {
            if argument.trim().is_empty() {
                Ok(Command::List)
            } else {
                Err(CommandError::Unknown)
            }
        }
        _ => Err(CommandError::Unknown),
    }
}
`;

const todo = `use crate::command::{Command, CommandError};

#[derive(Debug, PartialEq, Eq)]
pub(crate) struct Task {
    pub(crate) title: String,
    pub(crate) done: bool,
}

#[derive(Debug, Default, PartialEq, Eq)]
pub struct Todo {
    pub(crate) tasks: Vec<Task>,
}

impl Todo {
    pub fn new() -> Todo {
        Todo { tasks: Vec::new() }
    }

    pub fn apply(&mut self, command: Command) -> Result<String, CommandError> {
        match command {
            Command::Add(title) => {
                if title.trim().is_empty() || title.contains('\\n') || title.contains('\\r') {
                    return Err(CommandError::InvalidTitle);
                }
                self.tasks.push(Task { title, done: false });
                Ok(format!("added {}", self.tasks.len()))
            }
            Command::Done(id) => {
                if id == 0 {
                    return Err(CommandError::InvalidId);
                }
                let index = id - 1;
                if index >= self.tasks.len() {
                    return Err(CommandError::NotFound);
                }
                self.tasks[index].done = true;
                Ok(format!("done {}", id))
            }
            Command::List => {
                let mut output = String::new();
                let mut index = 0;
                while index < self.tasks.len() {
                    let task = &self.tasks[index];
                    let mark = if task.done { "x" } else { " " };
                    output.push_str(&format!("{} [{}] {}\\n", index + 1, mark, task.title));
                    index += 1;
                }
                Ok(output)
            }
        }
    }
}
`;

