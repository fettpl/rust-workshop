const storageSolution = `use crate::todo::{Task, Todo};
use std::fs::{self, OpenOptions};
use std::io::{ErrorKind, Write};

#[derive(Debug, PartialEq, Eq)]
pub enum FormatError {
    InvalidHeader,
    MissingFinalNewline,
    InvalidRow(usize),
    InvalidStatus(usize),
    InvalidTitle(usize),
}

#[derive(Debug)]
pub enum StorageError {
    Io(std::io::Error),
    Format(FormatError),
}

pub fn encode(todo: &Todo) -> String {
    let mut text = String::from("RUST_TODO_V1\\n");
    for task in &todo.tasks {
        let status = if task.done { "1" } else { "0" };
        text.push_str(status);
        text.push('\\t');
        text.push_str(&task.title);
        text.push('\\n');
    }
    text
}

pub fn decode(text: &str) -> Result<Todo, FormatError> {
    let rows = match text.strip_prefix("RUST_TODO_V1\\n") {
        Some(rows) => rows,
        None => return Err(FormatError::InvalidHeader),
    };
    if !text.ends_with('\\n') {
        return Err(FormatError::MissingFinalNewline);
    }
    let mut todo = Todo::new();
    for (index, row) in rows.split_terminator('\\n').enumerate() {
        let line_number = index + 2;
        let (status, title) = match row.split_once('\\t') {
            Some(parts) => parts,
            None => return Err(FormatError::InvalidRow(line_number)),
        };
        let done = match status {
            "0" => false,
            "1" => true,
            _ => return Err(FormatError::InvalidStatus(line_number)),
        };
        if title.trim().is_empty() || title.contains('\\n') || title.contains('\\r') {
            return Err(FormatError::InvalidTitle(line_number));
        }
        todo.tasks.push(Task {
            title: String::from(title),
            done,
        });
    }
    Ok(todo)
}

pub fn load(path: &str) -> Result<Todo, StorageError> {
    let text = match fs::read_to_string(path) {
        Ok(text) => text,
        Err(error) if error.kind() == ErrorKind::NotFound => return Ok(Todo::new()),
        Err(error) => return Err(StorageError::Io(error)),
    };
    match decode(&text) {
        Ok(todo) => Ok(todo),
        Err(error) => Err(StorageError::Format(error)),
    }
}

pub fn save(path: &str, todo: &Todo) -> Result<(), StorageError> {
    let temporary_path = format!("{path}.tmp");
    let mut file = match OpenOptions::new()
        .write(true)
        .create_new(true)
        .open(&temporary_path)
    {
        Ok(file) => file,
        Err(error) => return Err(StorageError::Io(error)),
    };

    // Only remove a temporary file that this call created successfully.
    let text = encode(todo);
    if let Err(error) = file.write_all(text.as_bytes()) {
        drop(file);
        let _ = fs::remove_file(&temporary_path);
        return Err(StorageError::Io(error));
    }
    if let Err(error) = file.sync_all() {
        drop(file);
        let _ = fs::remove_file(&temporary_path);
        return Err(StorageError::Io(error));
    }
    drop(file);
    if let Err(error) = fs::rename(&temporary_path, path) {
        let _ = fs::remove_file(&temporary_path);
        return Err(StorageError::Io(error));
    }
    Ok(())
}
`;

